// ── 書式 ──
export function fmtMoney(amount: number, locale: Locale, currency = "JPY") {
  return new Intl.NumberFormat(locale === "ja" ? "ja-JP" : "en-US", { style: "currency", currency, maximumFractionDigits: 0 }).format(amount);
}
export function fmtNumber(n: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "ja" ? "ja-JP" : "en-US").format(n);
}
export function fmtPercent(ratio: number, locale: Locale, signed = false) {
  const s = new Intl.NumberFormat(locale === "ja" ? "ja-JP" : "en-US", { style: "percent", maximumFractionDigits: 1, signDisplay: signed ? "exceptZero" : "auto" }).format(ratio);
  return s;
}
export function fmtDate(iso: string | undefined, locale: Locale, withTime = false) {
  if (!iso) return "—";
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00` : iso);
  if (Number.isNaN(d.getTime())) return iso;
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-GB", {
    year: "numeric",
    month: "short",
    day: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(d);
}
export function fmtShortDate(iso: string, locale: Locale) {
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00` : iso);
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-GB", { month: "numeric", day: "numeric" }).format(d);
}
export function fmtMonth(ym: string, locale: Locale) {
  const d = new Date(`${ym}-01T00:00:00`);
  return new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-GB", { year: "2-digit", month: "short" }).format(d);
}
